"""Rebuild the tactic routers and per-stage pick lists from every <library>/<slug>/TACTIC.md.
Usage: python3 Workflow/Tools/tactics/build_index.py   (or: tactics.py build)

Writes (only between the pick-list markers of the two routers, and whole files under picks/):
  Tactics/INDEX.md          long-form router: stage → pick-list file, plus the core checks
  Tactics/SHORTS-INDEX.md   short-form router, the same
  Tactics/picks/long-<stage>.md, picks/short-<stage>.md   one pick list per stage (group notes + table)
A step loads its router's core list and the one stage file it needs; `tactics.py find/show` narrows further.
Group notes come from index-notes.md / shorts-index-notes.md ('### <group title>' sections)."""
import re, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from tactics import ROOT, load  # noqa: E402

PICKS = ROOT / 'picks'
ROLES = ['check', 'attention', 'curiosity', 'benefit', 'credibility', 'process']
LONG_GROUPS = [('idea', 'Idea'), ('title', 'Title and thumbnail'), ('hook', 'Hook (intro)'), ('structure', 'Structure and script'),
               ('visuals', 'Visuals'), ('editing', 'Editing'), ('sound', 'Sound'), ('ending', 'Ending')]
SHORT_GROUPS = [('idea', 'Ideas, formats and series'), ('hook', 'Hook'), ('script', 'Script and structure'),
                ('filming', 'Filming and delivery'), ('editing', 'Edit, text and captions'), ('sound', 'Sound'),
                ('posting', 'Posting and engagement'), ('analytics', 'Analytics')]
SHORT_ALIASES = {'format': 'idea', 'series': 'idea', 'personal': 'filming', 'text-captions': 'editing', 'visuals': 'editing',
                 'engagement': 'posting', 'structure': 'script', 'title': 'posting', 'thumbnail': 'posting', 'ending': 'script'}


def long_group(t):
    if t['lib'] == 'ideas':
        return 'idea'
    if t['lib'] == 'titles-thumbnails':
        return 'title'
    return next((s for s in t['stages'] if s in dict(LONG_GROUPS) and s not in ('idea', 'title', 'thumbnail')), 'structure')


def short_group(t):
    for s in t['stages']:
        s = SHORT_ALIASES.get(s, s)
        if s in dict(SHORT_GROUPS):
            return s
    return 'script'


def notes(file):
    out = {}
    if file.exists():
        for block in re.split(r'^### ', file.read_text(), flags=re.M)[1:]:
            title, _, body = block.partition('\n')
            out[title.strip()] = body.strip()
    return out


def row(t, fmt, g):
    badge = '' if t['status'] == 'candidate' else f' **[{t["status"]}]**'
    other = sorted(f for f in t['formats'] if f != fmt)
    cross = f' *(also {", ".join(other)}-form)*' if other else ''
    core = ' ●' if t['core'] else ''
    tags = ', '.join(x for x in [f"face: {'/'.join(sorted(t['face']))}" if t['face'] != {'any'} else '',
                                 f"mode: {'/'.join(sorted(t['mode']))}" if t['mode'] != {'any'} else ''] if x)
    also = ', '.join(s for s in t['stages'] if s != g and not (g == 'title' and s == 'thumbnail'))
    link = f'../{t["lib"]}/{t["slug"]}/TACTIC.md'
    cells = [f'[{t["name"]}]({link}){core}{badge}{cross}']
    if g == 'title':
        cells.append(t['role'])
    cells += [also + (f' · {tags}' if tags else ''), t['pick']]
    return (ROLES.index(t['role']) if t['role'] in ROLES else 99, t['name'].lower(), '| ' + ' | '.join(cells) + ' |')


def build(fmt, router, groups, group_of, notes_file):
    ts = [t for t in load() if fmt in t['formats']]
    rows = {g: [] for g, _ in groups}
    for t in ts:
        g = group_of(t)
        rows[g].append(row(t, fmt, g))
    gnotes = notes(notes_file)
    PICKS.mkdir(exist_ok=True)
    table = ['| Stage | Pick list | Tactics |', '| --- | --- | --- |']
    for g, title in groups:
        if not rows[g]:
            continue
        f = PICKS / f'{fmt}-{g}.md'
        body = [f'# {title} — {fmt}-form tactics', '',
                f'Generated by `Workflow/Tools/tactics/build_index.py`; edit the TACTIC.md files, not this. ● = core check '
                f'(applies every time). Open a tactic with `python3 Workflow/Tools/tactics/tactics.py show <slug>`.', '']
        if title in gnotes:
            body += [gnotes[title], '']
        body += (['| Tactic | Role | Also · tags | Pick |', '| --- | --- | --- | --- |'] if g == 'title'
                 else ['| Tactic | Also · tags | Pick |', '| --- | --- | --- |'])
        body += [r for *_, r in sorted(rows[g])]
        f.write_text('\n'.join(body) + '\n')
        table.append(f'| {title} | [`picks/{f.name}`](picks/{f.name}) | {len(rows[g])} |')
    core = sorted((t for t in ts if t['core']), key=lambda t: (group_of(t), t['name']))
    out = ['## Pick lists by stage', '',
           'Load only the stage you are working on, plus the core checks below. To narrow further, use '
           '`python3 Workflow/Tools/tactics/tactics.py find --format ' + fmt + ' --stage <stage> [--face …] [--mode …] [--text …]`, '
           'then `tactics.py show <slug>` for the working card. Once a brief or plan has chosen its tactics, later steps read '
           'that shortlist, not these lists. Rebuilt by `build_index.py`; don\'t edit by hand.', ''] + table + ['',
           f'### Core checks ({len(core)}): apply every time', '']
    out += [f'- `{t["slug"]}` ({dict(groups).get(group_of(t), group_of(t))}): {t["pick"]}' for t in core] or ['- (none marked yet)']
    text = router.read_text()
    A, B = '<!-- pick-list:start -->', '<!-- pick-list:end -->'
    router.write_text(text[:text.index(A) + len(A)] + '\n' + '\n'.join(out) + '\n' + text[text.index(B):])
    return {title: len(rows[g]) for g, title in groups if rows[g]} | {'core': len(core)}


if __name__ == '__main__':
    print('long ', build('long', ROOT / 'INDEX.md', LONG_GROUPS, long_group, ROOT / 'index-notes.md'))
    print('short', build('short', ROOT / 'SHORTS-INDEX.md', SHORT_GROUPS, short_group, ROOT / 'shorts-index-notes.md'))
